"""Finite Bernstein-cover witnesses for the unique-top ``L=2,3`` rows.

Each entry is ``(path, closure, multiplier)``.  Paths encode midpoint
subdivisions in the chart's stated axis cycle.  A multiplier is stored as a
numerator-denominator pair so the exact verifier never parses a decimal.
"""

from __future__ import annotations


def _parse_witness(text: str):
    rows = []
    for raw in text.split(";"):
        fields = raw.split()
        if len(fields) == 2:
            path, closure = fields
            multiplier = None
        elif len(fields) == 3:
            path, closure, value = fields
            multiplier = (int(value), 1)
        else:  # pragma: no cover - constant data are checked by unit tests
            raise AssertionError("malformed Bernstein witness")
        rows.append((path, closure, multiplier))
    return tuple(rows)


